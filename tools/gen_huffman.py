#!/usr/bin/env python3
"""Generate Rust Huffman tables from LibAtrac9's huffCodes.c.

Extracts every `XxxBits`/`XxxCodes` array and emits them as Rust `static`s, plus
builder functions for the codebook metadata (hand-encoded below from the C
`HuffmanCodebook` tables, which are small). Run from the repo root:

    python tools/gen_huffman.py
"""
import os
import re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, "reference", "LibAtrac9", "C", "src", "huffCodes.c")
OUT = os.path.join(HERE, "crates", "at9codec", "src", "decode", "huffman_tables.rs")


def rn(name):
    """Deterministic C-name -> Rust static name (used for both emit + refs)."""
    return re.sub(r"(?<=[a-z])(?=[A-Z])", "_", name).upper()


def extract_arrays(text):
    arrays = {}
    pat = re.compile(
        r"static const (uint8_t|uint16_t)\s+(\w+)\s*\[\d*\]\s*=\s*\{([^}]*)\}\s*;",
        re.DOTALL,
    )
    for m in pat.finditer(text):
        ctype, name, body = m.group(1), m.group(2), m.group(3)
        vals = [int(v, 0) for v in body.replace("\n", " ").split(",") if v.strip()]
        rust_ty = "u8" if ctype == "uint8_t" else "u16"
        arrays[name] = (rust_ty, vals)
    return arrays


# Codebook metadata: (base_name, value_count, value_count_power, value_bits,
# value_max, max_bit_size). None = empty slot. Transcribed from the
# HuffmanCodebook tables at the end of huffCodes.c.
SF_UNSIGNED = [
    None,
    ("ScaleFactorsA1", 1, 0, 1, 2, 1),
    ("ScaleFactorsA2", 1, 0, 2, 4, 3),
    ("ScaleFactorsA3", 1, 0, 3, 8, 6),
    ("ScaleFactorsA4", 1, 0, 4, 16, 8),
    ("ScaleFactorsA5", 1, 0, 5, 32, 8),
    ("ScaleFactorsA6", 1, 0, 6, 64, 8),
]
SF_SIGNED = [
    None,
    None,
    ("ScaleFactorsB2", 1, 0, 2, 4, 2),
    ("ScaleFactorsB3", 1, 0, 3, 8, 6),
    ("ScaleFactorsB4", 1, 0, 4, 16, 8),
    ("ScaleFactorsB5", 1, 0, 5, 32, 8),
]
# Spectrum[set][precision][codebookIndex]; precision 0,1 rows are all empty.
SPECTRUM = [
    [  # set A
        [None, None, None, None],
        [None, None, None, None],
        [("SpectrumA21", 2, 1, 2, 4, 3), ("SpectrumA22", 4, 2, 2, 4, 8), ("SpectrumA23", 4, 2, 2, 4, 9), ("SpectrumA24", 4, 2, 2, 4, 10)],
        [("SpectrumA31", 2, 1, 3, 8, 7), ("SpectrumA32", 2, 1, 3, 8, 7), ("SpectrumA33", 2, 1, 3, 8, 8), ("SpectrumA34", 2, 1, 3, 8, 10)],
        [("SpectrumA41", 2, 1, 4, 16, 9), ("SpectrumA42", 2, 1, 4, 16, 10), ("SpectrumA43", 2, 1, 4, 16, 10), ("SpectrumA44", 2, 1, 4, 16, 10)],
        [("SpectrumA51", 1, 0, 5, 32, 6), ("SpectrumA52", 1, 0, 5, 32, 6), ("SpectrumA53", 1, 0, 5, 32, 7), ("SpectrumA54", 1, 0, 5, 32, 8)],
        [("SpectrumA61", 1, 0, 6, 64, 7), ("SpectrumA62", 1, 0, 6, 64, 7), ("SpectrumA63", 1, 0, 6, 64, 8), ("SpectrumA64", 1, 0, 6, 64, 9)],
        [("SpectrumA71", 1, 0, 7, 128, 8), ("SpectrumA72", 1, 0, 7, 128, 8), ("SpectrumA73", 1, 0, 7, 128, 9), ("SpectrumA74", 1, 0, 7, 128, 10)],
    ],
    [  # set B
        [None, None, None, None],
        [None, None, None, None],
        [None, ("SpectrumB22", 4, 2, 2, 4, 10), ("SpectrumB23", 4, 2, 2, 4, 10), ("SpectrumB24", 4, 2, 2, 4, 10)],
        [None, ("SpectrumB32", 2, 1, 3, 8, 9), ("SpectrumB33", 2, 1, 3, 8, 10), ("SpectrumB34", 2, 1, 3, 8, 10)],
        [None, ("SpectrumB42", 2, 1, 4, 16, 10), ("SpectrumB43", 2, 1, 4, 16, 10), ("SpectrumB44", 2, 1, 4, 16, 10)],
        [None, ("SpectrumB52", 1, 0, 5, 32, 7), ("SpectrumB53", 1, 0, 5, 32, 8), ("SpectrumB54", 1, 0, 5, 32, 9)],
        [None, ("SpectrumB62", 1, 0, 6, 64, 8), ("SpectrumB63", 1, 0, 6, 64, 9), ("SpectrumB64", 1, 0, 6, 64, 10)],
        [None, ("SpectrumB72", 1, 0, 7, 128, 9), ("SpectrumB73", 1, 0, 7, 128, 10), ("SpectrumB74", 1, 0, 7, 128, 10)],
    ],
]


def meta_expr(entry):
    if entry is None:
        return "None"
    base, vc, vcp, vb, vm, mbs = entry
    return (
        f"Some(CodebookMeta {{ bits: &{rn(base + 'Bits')}, codes: &{rn(base + 'Codes')}, "
        f"value_count: {vc}, value_count_power: {vcp}, value_bits: {vb}, "
        f"value_max: {vm}, max_bit_size: {mbs} }})"
    )


def main():
    with open(SRC, "r", encoding="utf-8", errors="replace") as f:
        text = f.read()
    arrays = extract_arrays(text)

    # Only emit arrays that the metadata actually references (keeps the file lean).
    needed = set()
    for grp in (SF_UNSIGNED, SF_SIGNED):
        for e in grp:
            if e:
                needed.add(e[0] + "Bits")
                needed.add(e[0] + "Codes")
    for s in SPECTRUM:
        for row in s:
            for e in row:
                if e:
                    needed.add(e[0] + "Bits")
                    needed.add(e[0] + "Codes")

    lines = [
        "// @generated by tools/gen_huffman.py from LibAtrac9 huffCodes.c — do not edit.",
        "#![allow(clippy::all)]",
        "#![cfg_attr(rustfmt, rustfmt_skip)]",
        "use super::huffman::CodebookMeta;",
        "",
    ]
    for name in sorted(needed):
        if name not in arrays:
            raise SystemExit(f"missing array in C source: {name}")
        ty, vals = arrays[name]
        joined = ", ".join(str(v) for v in vals)
        lines.append(f"pub static {rn(name)}: [{ty}; {len(vals)}] = [{joined}];")
    lines.append("")

    # sf_unsigned
    lines.append("pub fn sf_unsigned() -> [Option<CodebookMeta>; 7] {")
    lines.append("    [" + ", ".join(meta_expr(e) for e in SF_UNSIGNED) + "]")
    lines.append("}")
    lines.append("")
    lines.append("pub fn sf_signed() -> [Option<CodebookMeta>; 6] {")
    lines.append("    [" + ", ".join(meta_expr(e) for e in SF_SIGNED) + "]")
    lines.append("}")
    lines.append("")
    lines.append("pub fn spectrum() -> [[[Option<CodebookMeta>; 4]; 8]; 2] {")
    lines.append("    [")
    for s in SPECTRUM:
        lines.append("        [")
        for row in s:
            lines.append("            [" + ", ".join(meta_expr(e) for e in row) + "],")
        lines.append("        ],")
    lines.append("    ]")
    lines.append("}")
    lines.append("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT} ({len(needed)} arrays)")


if __name__ == "__main__":
    main()
